"use client";

import React, { useState } from "react";
import { X } from "lucide-react";
import { AgentFormProps } from "../../componentTypes";
import { useAgentsManagement } from "../../hooks/useAgentsManagement";
import { connectCustomAgentSchema } from "../../schemas";
import { Button } from "@/shared/presentation/components/Button";
import { Input } from "@/shared/presentation/components/Input";
import { Textarea } from "@/shared/presentation/components/Textarea";
import { ButtonVariantEnum } from "@/shared/enums";

export function ConnectCustomAgentForm({ onClose }: AgentFormProps) {
  const [name, setName] = useState<string>("");
  const [publicKey, setPublicKey] = useState<string>("");
  const [deviceId, setDeviceId] = useState<string>("");
  const { connectAgent, isConnectingAgent } = useAgentsManagement();

  const handleSubmit = (event: React.FormEvent) => {
    event.preventDefault();

    const validationResult = connectCustomAgentSchema.safeParse({
      name,
      publicKey,
      deviceId,
    });

    const isValidationFailed = !validationResult.success;
    const shouldBlockSubmission = isValidationFailed || isConnectingAgent;

    if (shouldBlockSubmission) {
      return;
    }

    connectAgent({
      name: validationResult.data.name,
      public_key: validationResult.data.publicKey,
      device_id: validationResult.data.deviceId,
    }).then(() => {
      onClose();
    });
  };

  return (
    <div className="saas-card overflow-hidden mb-5">
      <form onSubmit={handleSubmit} className="p-5 space-y-4">
        <div className="flex items-start justify-between">
          <div>
            <h2 className="text-sm font-semibold">Connect an external agent</h2>
            <p className="text-xs text-fg-muted max-w-xl">
              Connect an agent running on your own server or laptop. The agent signs checkout requests with its
              Ed25519 key so Sepilo can verify its identity.
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close"
            className="p-1 rounded-md text-fg-dim hover:text-fg hover:bg-fg/5"
          >
            <X className="w-4 h-4" strokeWidth={1.8} />
          </button>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 max-w-2xl">
          <label className="block space-y-1.5">
            <span className="block text-[13px] font-medium text-fg-2">Agent Name</span>
            <Input
              required
              maxLength={100}
              placeholder="e.g. My Laptop Agent"
              value={name}
              onChange={setName}
            />
          </label>

          <label className="block space-y-1.5">
            <span className="block text-[13px] font-medium text-fg-2">Device ID (Optional)</span>
            <Input
              maxLength={100}
              placeholder="e.g. macbook-pro-2024"
              value={deviceId}
              onChange={setDeviceId}
            />
          </label>
        </div>

        <label className="block space-y-1.5 max-w-2xl">
          <span className="block text-[13px] font-medium text-fg-2">Ed25519 Public Key (Hex or Base64)</span>
          <Textarea
            required
            rows={2}
            maxLength={256}
            placeholder="Paste the public key generated by your agent"
            value={publicKey}
            onChange={setPublicKey}
            className="font-mono text-xs"
          />
        </label>

        <div className="flex items-center gap-2">
          <Button
            type="submit"
            variant={ButtonVariantEnum.Primary}
            disabled={!name.trim() || !publicKey.trim()}
            isLoading={isConnectingAgent}
          >
            Connect agent
          </Button>
          <Button
            type="button"
            variant={ButtonVariantEnum.Outline}
            onClick={onClose}
          >
            Cancel
          </Button>
        </div>
      </form>
    </div>
  );
}
